/* ------------------------------------------------------------------
   Sample thumbnails.
   Generated as inline SVG so the demo works offline with no broken
   links. In production `thumbnail` is a normal image URL (uploaded
   file or a pasted link). Two programs below have none on purpose,
   so you can see the initials fallback and the "add a thumbnail" hint.
------------------------------------------------------------------- */
function thumb(glyph, label, from, to) {
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 640 360">` +
    `<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1">` +
    `<stop offset="0" stop-color="${from}"/><stop offset="1" stop-color="${to}"/>` +
    `</linearGradient></defs>` +
    `<rect width="640" height="360" fill="url(#g)"/>` +
    `<circle cx="540" cy="70" r="120" fill="#fff" opacity=".10"/>` +
    `<circle cx="90" cy="330" r="150" fill="#fff" opacity=".08"/>` +
    `<rect x="40" y="40" width="64" height="8" rx="4" fill="#fff" opacity=".5"/>` +
    `<rect x="40" y="60" width="40" height="8" rx="4" fill="#fff" opacity=".3"/>` +
    `<text x="320" y="215" text-anchor="middle" font-family="Menlo,Consolas,monospace" ` +
    `font-size="124" font-weight="800" fill="#fff">${glyph}</text>` +
    `<text x="40" y="326" font-family="Arial,sans-serif" font-size="26" ` +
    `font-weight="700" fill="#fff" opacity=".9">${label}</text>` +
    `</svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

